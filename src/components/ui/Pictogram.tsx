/** Icône à la taille du texte autour (1em) ; `fallback` pour un emoji sans icône. */
export function Pictogram({ of, fallback = UtensilsCrossed, className }: { of?: string | null; fallback?: LucideIcon; className?: string }) {
  const Icon = ICONS[(of ?? "").replace(/️/g, "")] ?? fallback;
  return <Icon size="1em" strokeWidth={1.8} aria-hidden="true" className={className} />;
}

